// Makes the constant tables Wisp's renderer needs, and the data the native check runs on.
//   node look/port/gen_tables.mjs
// Writes:
//   firmware/lib/wisp/wisp_tables.h   sine table, the sunflower homes of the 512 motes (model-independent)
//   firmware/lib/wisp/wisp_mind.h     the model's own mean, spread, unit order and two principal directions,
//                                     computed exactly as look/sketch2/index.html does (the MIND block, lifted)
//   look/port/mind.bin                the 1,800 real states and their entropies, for wisp_png
//   look/port/scratch/paper-js.bin    the sketch's paper as RGB565, for a bit-for-bit check of wisp_paper()
// Re-run when the model changes (its dump is look/sketch/mind-states.js).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import vm from 'node:vm';

const here = new URL('.', import.meta.url).pathname;
const look = join(here, '..');
const lib = join(look, '..', 'firmware', 'lib', 'wisp');
mkdirSync(join(here, 'scratch'), { recursive: true });

const window = {};
vm.runInNewContext(readFileSync(join(look, 'sketch', 'mind-states.js'), 'utf8'), { window });
const atob = (s) => Buffer.from(s, 'base64').toString('binary');
const clamp = (v, a, b) => v < a ? a : v > b ? b : v;

// ---- lifted from look/sketch2/index.html (the mind, real states), unchanged ----
const MS = window.MIND, U = MS.H, NS = MS.steps;
const RAW = (() => { const b = atob(MS.h), a = new Int8Array(b.length); for (let i = 0; i < b.length; i++) a[i] = (b.charCodeAt(i) << 24) >> 24; return a; })();
const hAt = (k, i) => RAW[(k % NS) * U + i] / 127;
const MIND = (() => {
  const mean = new Float32Array(U), e8 = new Float32Array(U), v8 = new Float32Array(U);
  for (let s = 0; s < NS; s++) for (let i = 0; i < U; i++) mean[i] += hAt(s, i) / NS;
  const X = [];
  for (let s = 0; s < NS; s++) { for (let i = 0; i < U; i++) { e8[i] += (hAt(s, i) - e8[i]) / 8; if (s > 30) v8[i] += (e8[i] - mean[i]) ** 2; } if (s > 30 && s % 6 === 0) X.push(Float32Array.from(e8, (v, i) => v - mean[i])); }
  const sd8 = v8.map(v => Math.sqrt(v / (NS - 31)) + 1e-4);
  const pcs = [];
  for (let k = 0; k < 2; k++) {
    let v = Float32Array.from({ length: U }, (_, i) => Math.sin(i * (k + 1.7)));
    for (let it = 0; it < 25; it++) {
      const w = new Float32Array(U);
      for (const x of X) { let d = 0; for (let i = 0; i < U; i++) d += x[i] * v[i]; for (let i = 0; i < U; i++) w[i] += d * x[i]; }
      for (const p of pcs) { let d = 0; for (let i = 0; i < U; i++) d += w[i] * p[i]; for (let i = 0; i < U; i++) w[i] -= d * p[i]; }
      let n = 0; for (let i = 0; i < U; i++) n += w[i] * w[i]; n = Math.sqrt(n); for (let i = 0; i < U; i++) v[i] = w[i] / n;
    }
    let ss = 0; for (const x of X) { let d = 0; for (let i = 0; i < U; i++) d += x[i] * v[i]; ss += d * d; }
    pcs.push(v); v.sd = Math.sqrt(ss / X.length);
  }
  const order = [...Array(U).keys()].sort((a, b) => Math.atan2(pcs[1][a], pcs[0][a]) - Math.atan2(pcs[1][b], pcs[0][b]));
  const ent = [...MS.ent].sort((a, b) => a - b), E10 = ent[Math.floor(ent.length * 0.1)], E90 = ent[Math.floor(ent.length * 0.9)];
  return { mean, sd8, pcs, order, E10, E90 };
})();
// ---- end of the lifted block ----

const f = (v) => { let s = (+v).toPrecision(7); if (!/[.e]/.test(s)) s += '.0'; return s.replace(/e/, 'e') + 'f'; };
const rows = (arr, fmt, per = 8) => { const out = []; for (let i = 0; i < arr.length; i += per) out.push('  ' + Array.from(arr.slice(i, i + per), fmt).join(', ') + ','); return out.join('\n'); };

// ---- wisp_tables.h: nothing here depends on the model ----
const N = 512;
const sinT = Array.from({ length: 256 }, (_, i) => Math.sin(i * 2 * Math.PI / 256));
const HX = [], HY = [], RR = [];
for (let i = 0; i < N; i++) { const r = Math.sqrt((i + 0.5) / N), a = i * 2.39996; HX.push(Math.round(Math.cos(a) * r * 16384)); HY.push(Math.round(Math.sin(a) * r * 16384)); RR.push(Math.min(255, Math.round(r * 256))); }
writeFileSync(join(lib, 'wisp_tables.h'), `// Generated by look/port/gen_tables.mjs. Do not edit by hand.
// Constant tables for wisp.cpp; they live in flash, not in working memory.
#pragma once
#include <stdint.h>

// sin(i * 2pi / 256)
static const float WISP_SIN[256] = {
${rows(sinT, f)}
};

// each mote's home on a sunflower spiral in a unit disc (the sketch's HX, HY), Q14
static const int16_t WISP_HOME_X[${N}] = {
${rows(HX, String, 16)}
};
static const int16_t WISP_HOME_Y[${N}] = {
${rows(HY, String, 16)}
};
// distance of each home from the centre, Q8 (sqrt((i + 0.5) / 512))
static const uint8_t WISP_HOME_R[${N}] = {
${rows(RR, String, 16)}
};
`);

// ---- wisp_mind.h: the model's own statistics, from its real states ----
const inv = Array.from(MIND.sd8, (s) => 1 / (1.5 * s));
writeFileSync(join(lib, 'wisp_mind.h'), `// Generated by look/port/gen_tables.mjs from look/sketch/mind-states.js (${NS} real states of a
// ${U}-unit mind). Do not edit by hand; re-run the generator when the model changes.
// Used only when the state handed to wisp_frame has exactly WISP_MIND_N numbers; otherwise
// wisp.cpp falls back to a mean of 0, a fixed spread, units in their own order and no lean.
#pragma once
#include <stdint.h>

#define WISP_MIND_N ${U}

// the model's mean state
static const float WISP_MIND_MEAN[${U}] = {
${rows(MIND.mean, f)}
};
// 1 / (1.5 x the spread of the state smoothed over 8 pieces): one unit of "dev"
static const float WISP_MIND_INV[${U}] = {
${rows(inv, f)}
};
// the unit each mote rides, sorted by its angle in the plane of the first two principal directions
static const uint16_t WISP_MIND_ORDER[${U}] = {
${rows(MIND.order, String, 16)}
};
// the first two principal directions of the smoothed state, and the spread along each
static const float WISP_MIND_PC0[${U}] = {
${rows(MIND.pcs[0], f)}
};
static const float WISP_MIND_PC1[${U}] = {
${rows(MIND.pcs[1], f)}
};
static const float WISP_MIND_PCSD[2] = {${f(MIND.pcs[0].sd)}, ${f(MIND.pcs[1].sd)}};
`);

// ---- mind.bin: int32 H, int32 steps, float E10, float E90, float ent[steps], int8 h[steps * H] ----
{
  const head = Buffer.alloc(16); head.writeInt32LE(U, 0); head.writeInt32LE(NS, 4); head.writeFloatLE(MIND.E10, 8); head.writeFloatLE(MIND.E90, 12);
  const ent = Buffer.alloc(NS * 4); for (let i = 0; i < NS; i++) ent.writeFloatLE(MS.ent[i], i * 4);
  writeFileSync(join(here, 'mind.bin'), Buffer.concat([head, ent, Buffer.from(RAW.buffer, RAW.byteOffset, RAW.byteLength)]));
}

// ---- paper-js.bin: the sketch's paper, masked to 16 bits as present() does, RGB565 little-endian ----
{
  const W = 240, H = 135, out = Buffer.alloc(W * H * 2);
  for (let i = 0; i < W * H; i++) {
    const y = (i / W) | 0, x = i % W; const n = ((x * 73856093) ^ (y * 19349663)) >>> 0, fv = (n % 7) - 3, fib = ((x + y * 3) % 23 === 0) ? -4 : 0;
    const r = (246 + fv + fib) & 0xF8, g = (235 + fv + fib) & 0xFC, b = (220 + fv + fib) & 0xF8;
    out.writeUInt16LE((r << 8) | (g << 3) | (b >> 3), i * 2);
  }
  writeFileSync(join(here, 'scratch', 'paper-js.bin'), out);
}

const sd = [...MIND.sd8].sort((a, b) => a - b);
console.log(`mind ${U} units, ${NS} states; E10 ${MIND.E10.toFixed(3)} E90 ${MIND.E90.toFixed(3)}; sd8 min ${sd[0].toFixed(4)} median ${sd[U >> 1].toFixed(4)} max ${sd[U - 1].toFixed(4)}; pc sd ${MIND.pcs[0].sd.toFixed(3)} ${MIND.pcs[1].sd.toFixed(3)}`);
