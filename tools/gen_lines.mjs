// Turns character/lines.json into firmware/src/lines_data.h. Run after editing the lines:
//   node tools/gen_lines.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const lines = JSON.parse(readFileSync(join(root, 'character/lines.json'), 'utf8'))
const moods = ['calm', 'happy', 'delighted', 'curious', 'thinking', 'sleepy', 'surprised', 'sad', 'cheeky', 'tender', 'alert']
const cstr = (s) => '"' + s.replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"'
const ident = (k) => 'L_' + k.replace(/[^a-z0-9]/gi, '_')

let out = '// Generated by tools/gen_lines.mjs from character/lines.json. Edit that file, not this one.\n#pragma once\n#include "mind.h"\n\n'
let total = 0
const keys = Object.keys(lines)
for (const key of keys) {
  out += `static const Line ${ident(key)}[] = {\n`
  for (const l of lines[key]) {
    if (!moods.includes(l.mood)) throw new Error(`${key}: unknown mood ${l.mood}`)
    if (/[^\x20-\x7e]/.test(l.say)) throw new Error(`${key}: non-plain character in "${l.say}"`)
    out += `    {${cstr(l.say)}, ${l.mood.toUpperCase()}},\n`
    total++
  }
  out += '};\n'
}
out += '\nstruct LineSet {\n  const char *key;\n  const Line *lines;\n  uint8_t count;\n};\nstatic const LineSet LINE_SETS[] = {\n'
for (const key of keys) out += `    {${cstr(key)}, ${ident(key)}, ${lines[key].length}},\n`
out += `};\nstatic const int LINE_SET_COUNT = ${keys.length};\n`
writeFileSync(join(root, 'firmware/src/lines_data.h'), out)
console.log(`${keys.length} situations, ${total} lines -> firmware/src/lines_data.h`)
